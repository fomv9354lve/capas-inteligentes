"""CAPAS — the rule table as data (PLAN_v3 A1). Engine side.

docs/rule_table.json (generated by scripts/gen_rule_table.py from the engine) lists every rule that can write a
reason segment. This module turns a decision's reason into the ordered list of rules that fired, and states, for an
ACCEPT, which rules of the same claim type would have failed it. The certificate carries rules_fired and the table's
sha256, so a checker that never imports capas.py can replay the verdict from the table alone (CERTIFICATE_SPEC.md).
"""
from __future__ import annotations

import ast
import functools
import hashlib
import json
import re
from pathlib import Path
from typing import Any

_HERE = Path(__file__).resolve().parent
TABLE_PATH = _HERE / "docs" / "rule_table.json"


@functools.lru_cache(maxsize=1)
def table_text() -> str:
    """The published table (docs/rule_table.json); in an installed wheel, where docs/ is absent, the same bytes are
    rebuilt from capas.py's source (CI proves file == rebuild: scripts/gen_rule_table.py --check)."""
    if TABLE_PATH.is_file():
        return TABLE_PATH.read_text(encoding="utf-8")
    return dump(build())


@functools.lru_cache(maxsize=1)
def table() -> dict[str, Any]:
    return json.loads(table_text())


@functools.lru_cache(maxsize=1)
def table_sha256() -> str:
    return "sha256:" + hashlib.sha256(table_text().encode("utf-8")).hexdigest()


@functools.lru_cache(maxsize=1)
def _compiled() -> tuple[list[tuple[dict, re.Pattern]], list[tuple[dict, re.Pattern]]]:
    rules = table()["rules"]
    base = [(r, re.compile(r["pattern"], re.S)) for r in rules if r["stage"] == "base"]
    tail = [(r, re.compile(r["pattern"], re.S)) for r in rules if r["stage"] != "base"]
    return base, tail


# ---------------------------------------------------------------- table builder (reads capas.py, executes nothing)
# Generates docs/rule_table.json, the engine's rules AS DATA (PLAN_v3 A1, council 8/8, 2026-10-14).
#
# Every place in capas.decide_external_claim() that writes the verdict's reason is one rule. The generator reads the
# function's syntax tree (no execution) and records, per rule:
#   id         "R" + first 10 hex of sha256(pattern)   (a changed reason text is a new rule id)
#   version    1
#   stage      base (writes the first reason segment) | downgrade (appends "; ..." and may change the verdict) |
#              annotate (appends "; ..." and never changes it)
#   claim_type the claim type whose branch holds the rule, or null (any type)
#   verdict    base rules: the verdict they set
#   from / to  downgrade rules: the verdicts they act on and the verdict they leave (to = null: unchanged)
#   hold_class for rules that leave HOLD: field_absent (the evidence lacks something declarable) | engine_gap (the
#              engine cannot judge: unsupported type, missing dependency, no source root)
#   pattern    regex over one reason segment (literal text escaped, every interpolated value = (.+?))
# The PLAN_v3 stages are declared as data in capas_plan3.RULES and appended. OVERRIDES fixes what the syntax tree
# cannot see (a verdict decided in a sibling branch); scripts/check_rule_table.py proves the table against the engine on
# every payload in the repository, so an override that is wrong fails CI.
TABLE_VERSION = "capas-rule-table-v1"
VERDICTS = ("ACCEPT", "REWRITE", "REJECT", "HOLD")
ENGINE_GAP = re.compile(r"unsupported|no rule was applied|scipy|register an anchor contract|schema validation", re.I)
# pattern prefix -> fields to force (what the syntax tree cannot see). Every entry is proved by check_rule_table.py.
OVERRIDES: dict[str, dict] = {}


def _rx(node: ast.AST, src: str) -> tuple[str, bool]:
    """(regex, starts_with_reason) for a reason expression."""
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return re.escape(node.value), False
    if isinstance(node, ast.JoinedStr):
        parts, aug = [], False
        for i, v in enumerate(node.values):
            if isinstance(v, ast.Constant):
                parts.append(re.escape(v.value))
            elif isinstance(v, ast.FormattedValue):
                if i == 0 and isinstance(v.value, ast.Name) and v.value.id == "reason":
                    aug = True
                    continue
                parts.append("(.*?)")
        rx = "".join(parts)
        if aug:
            rx = rx[len(re.escape("; ")):] if rx.startswith(re.escape("; ")) else rx
        return rx, aug
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        a, aug = _rx(node.left, src)
        b, _ = _rx(node.right, src)
        return a + b, aug
    return "(.*?)", False


def _verdict_cond(test: ast.AST) -> set[str] | None:
    """Verdicts allowed by a condition on `verdict` (None = the condition says nothing about it)."""
    if isinstance(test, ast.BoolOp):
        sets = [s for s in (_verdict_cond(v) for v in test.values) if s is not None]
        if not sets:
            return None
        if isinstance(test.op, ast.And):
            out = set(VERDICTS)
            for s in sets:
                out &= s
            return out
        return set().union(*sets)
    if isinstance(test, ast.Compare) and isinstance(test.left, ast.Name) and test.left.id == "verdict" and len(test.ops) == 1:
        op, c = test.ops[0], test.comparators[0]
        vals = ({c.value} if isinstance(c, ast.Constant) else
                {e.value for e in c.elts if isinstance(e, ast.Constant)} if isinstance(c, (ast.Tuple, ast.List, ast.Set)) else None)
        if vals is None:
            return None
        if isinstance(op, (ast.Eq, ast.In)):
            return set(vals)
        if isinstance(op, (ast.NotEq, ast.NotIn)):
            return set(VERDICTS) - set(vals)
    return None


def _claim_type_cond(test: ast.AST) -> str | None:
    for n in ast.walk(test):
        if isinstance(n, ast.Compare) and isinstance(n.left, ast.Name) and n.left.id == "claim_type" and \
                isinstance(n.ops[0], ast.Eq) and isinstance(n.comparators[0], ast.Constant):
            return n.comparators[0].value
    return None


def build() -> dict:
    import capas_plan3
    src = (_HERE / "capas.py").read_text(encoding="utf-8")
    tree = ast.parse(src)
    fn = next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == "decide_external_claim")
    parent: dict[ast.AST, ast.AST] = {}
    for p in ast.walk(fn):
        for c in ast.iter_child_nodes(p):
            parent[c] = p
    rules, seen = [], set()

    def body_of(node):
        """The statement list that directly contains `node`, and its owner."""
        p = parent.get(node)
        for field in ("body", "orelse", "finalbody"):
            lst = getattr(p, field, None)
            if isinstance(lst, list) and node in lst:
                return lst, p, field
        return [], p, None

    def ancestors_ifs(node):
        out, n = [], node
        while n in parent:
            p = parent[n]
            if isinstance(p, ast.If):
                out.append((p, n in p.body))
            n = p
        return out

    for node in ast.walk(fn):
        tgt = node.targets[0] if isinstance(node, ast.Assign) and len(node.targets) == 1 else (
            node.target if isinstance(node, ast.AugAssign) else None)
        if not (isinstance(tgt, ast.Name) and tgt.id == "reason"):
            continue
        rx, aug = _rx(node.value, src)
        if aug and rx in ("(.*?)", ""):
            continue   # the composition point of capas_plan3 segments: those rules are declared in capas_plan3.RULES
        if isinstance(node, ast.AugAssign):
            aug = True
            rx = rx[len(re.escape("; ")):] if rx.startswith(re.escape("; ")) else rx
        def _vassign(st):
            return (st.value.value if isinstance(st, ast.Assign) and len(st.targets) == 1 and isinstance(st.targets[0], ast.Name)
                    and st.targets[0].id == "verdict" and isinstance(st.value, ast.Constant) else None)
        stmts, _, _ = body_of(node)
        to = None
        for st in stmts:
            if _vassign(st):
                to = _vassign(st)
        if to is None and not aug and not isinstance(node, ast.AugAssign):
            # a base reason whose verdict was set before the branch: nearest preceding assignment walking outwards,
            # stopping at the claim-type branch (never inheriting the function's initial HOLD across branches)
            n = node
            while to is None and n in parent and parent[n] is not fn:
                lst, owner, _ = body_of(n)
                if n in lst:
                    for st in reversed(lst[:lst.index(n)]):
                        if _vassign(st):
                            to = _vassign(st)
                            break
                if isinstance(owner, ast.If) and _claim_type_cond(owner.test):
                    break
                n = owner
        ifs = ancestors_ifs(node)
        ctype = next((c for c in (_claim_type_cond(i.test) for i, inb in ifs if inb) if c), None)
        frm = None
        for i, inb in ifs:
            s = _verdict_cond(i.test) if inb else None
            if s is not None:
                frm = s if frm is None else frm & s
        r = {"pattern": rx, "line": node.lineno}
        if aug:
            r.update(stage="downgrade" if to else "annotate", claim_type=ctype,
                     **({"from": sorted(frm) if frm is not None else sorted(set(VERDICTS) - {to}), "to": to} if to else {"from": None, "to": None}))
        else:
            r.update(stage="base", claim_type=ctype, verdict=to or "HOLD")
        rules.append(r)
    # the schema-error HOLD is written inside a dict literal, not by an assignment
    rules.insert(0, {"pattern": re.escape("input payload failed CAPAS schema validation"), "stage": "base",
                     "claim_type": None, "verdict": "HOLD", "line": None})
    for r in capas_plan3.RULES:
        e = {"pattern": r["pattern"], "stage": r["stage"], "claim_type": None, "from": r["from"], "to": r["to"],
             "line": None, "source": "capas_plan3.RULES", "label": r["label"], "giant": r["giant"]}
        if r.get("hold_class"):
            e["hold_class"] = r["hold_class"]
        rules.append(e)
    out = []
    for r in rules:
        for pre, fix in OVERRIDES.items():
            if r["pattern"].startswith(pre):
                r.update(fix)
        lands_hold = (r["stage"] == "base" and r.get("verdict") == "HOLD") or (r["stage"] == "downgrade" and r.get("to") == "HOLD")
        if lands_hold and "hold_class" not in r:
            r["hold_class"] = "engine_gap" if ENGINE_GAP.search(r["pattern"]) else "field_absent"
        r["id"] = "R" + hashlib.sha256(r["pattern"].encode()).hexdigest()[:10]
        r["version"] = 1
        r.setdefault("label", re.sub(r"\\(.)", r"\1", r["pattern"]).replace("(.+?)", "…")[:140])
        if r["id"] in seen:
            continue
        seen.add(r["id"])
        out.append({k: r[k] for k in ("id", "version", "stage", "claim_type", "verdict", "from", "to", "hold_class",
                                      "pattern", "label", "giant", "source", "line") if k in r})
    order = {"base": 0, "downgrade": 1, "annotate": 1}
    out.sort(key=lambda r: (order[r["stage"]], r["line"] or 10 ** 9))
    for r in out:
        r.pop("line", None)
    return {"table_version": TABLE_VERSION, "generated_from": "capas.decide_external_claim + capas_plan3.RULES",
            "semantics": "reason = base segment, then '; '-joined downgrade/annotate segments in order; the verdict is the "
                         "base rule's verdict, then each downgrade rule maps it (it must be in `from`) to `to`",
            "rules": out}


def dump(table: dict) -> str:
    return json.dumps(table, indent=1, ensure_ascii=False) + "\n"




def parse_reason(reason: str) -> list[str] | None:
    """Ordered rule ids whose segments compose `reason` exactly, or None when no composition exists. Segments are
    joined by '; ', which may also occur inside an interpolated value, so the parse backtracks over split points."""
    base, tail = _compiled()
    if not isinstance(reason, str):
        return None
    cuts = [m.start() for m in re.finditer("; ", reason)] + [len(reason)]

    @functools.lru_cache(maxsize=None)
    def rest(pos: int) -> tuple[str, ...] | None:
        if pos == len(reason):
            return ()
        if not reason.startswith("; ", pos):
            return None
        start = pos + 2
        for end in cuts:
            if end < start:
                continue
            seg = reason[start:end]
            for r, rx in tail:
                if rx.fullmatch(seg):
                    nxt = rest(end)
                    if nxt is not None:
                        return (r["id"],) + nxt
        return None

    for end in cuts:
        seg = reason[:end]
        for r, rx in base:
            if rx.fullmatch(seg):
                nxt = rest(end)
                if nxt is not None:
                    return [r["id"], *nxt]
    return None


def replay(rule_ids: list[str]) -> str | None:
    """Verdict implied by the rules in order (None if a rule is unknown or acts outside its `from` set)."""
    by_id = {r["id"]: r for r in table()["rules"]}
    if not rule_ids or rule_ids[0] not in by_id or by_id[rule_ids[0]]["stage"] != "base":
        return None
    v = by_id[rule_ids[0]]["verdict"]
    for rid in rule_ids[1:]:
        r = by_id.get(rid)
        if r is None or r["stage"] == "base":
            return None
        if r["stage"] == "downgrade":
            if v not in (r["from"] or []):
                return None
            v = r["to"]
    return v


def would_have_failed_if(claim_type: str, fired: list[str] | None) -> list[str]:
    """For an ACCEPT: the base rules of the same claim type that end in REJECT or REWRITE (what the evidence would
    have had to show for the claim to fail), then the count of downgrade rules that can act on an ACCEPT."""
    rules = table()["rules"]
    alts = [r["label"] for r in rules if r["stage"] == "base" and r.get("claim_type") == claim_type
            and r.get("verdict") in ("REJECT", "REWRITE") and (not fired or r["id"] != fired[0])]
    n_down = sum(1 for r in rules if r["stage"] == "downgrade" and "ACCEPT" in (r.get("from") or [])
                 and r.get("claim_type") in (None, claim_type))
    return alts + [f"or any of {n_down} downgrade rules that act on an ACCEPT (see docs/rule_table.json)"]


def hold_class(fired: list[str] | None) -> str | None:
    """field_absent | engine_gap for the rule that left the verdict at HOLD (the last one that set HOLD)."""
    if not fired:
        return None
    by_id = {r["id"]: r for r in table()["rules"]}
    cls = None
    for rid in fired:
        r = by_id.get(rid, {})
        if (r.get("stage") == "base" and r.get("verdict") == "HOLD") or (r.get("stage") == "downgrade" and r.get("to") == "HOLD"):
            cls = r.get("hold_class")
    return cls
